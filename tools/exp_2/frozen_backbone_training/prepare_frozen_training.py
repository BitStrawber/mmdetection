#!/usr/bin/env python3
from __future__ import annotations

import argparse
import os
from pathlib import Path
from typing import Any, Mapping, Sequence


BACKBONE_OPTIONS = {
    "resnet50": {
        "frozen_stages": 4,
        "norm_eval": True,
    },
    "vit_small": {
        "frozen_stages": 12,
        "norm_eval": None,
    },
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Extract detector backbone weights and create a frozen training config."
    )
    commands = parser.add_subparsers(dest="command", required=True)

    prepare = commands.add_parser("prepare")
    prepare.add_argument("--name", required=True)
    prepare.add_argument("--base-config", required=True)
    prepare.add_argument("--detector-checkpoint", required=True)
    prepare.add_argument("--backbone-output", required=True)
    prepare.add_argument("--config-output", required=True)
    prepare.add_argument(
        "--backbone-type",
        required=True,
        choices=sorted(BACKBONE_OPTIONS),
    )
    prepare.add_argument("--save-best", required=True)
    prepare.add_argument("--source-key", default="")
    prepare.add_argument("--overwrite", action="store_true")

    verify = commands.add_parser("verify")
    verify.add_argument("--checkpoint", required=True)
    verify.add_argument("--backbone", required=True)
    return parser.parse_args()


def _existing_file(value: str | Path) -> Path:
    path = Path(value).expanduser().resolve()
    if not path.is_file() or path.stat().st_size <= 0:
        raise FileNotFoundError(f"Required file is missing or empty: {path}")
    return path


def _atomic_torch_save(value: Any, path: Path) -> None:
    import torch

    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    torch.save(value, temporary)
    os.replace(str(temporary), str(path))


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    os.replace(str(temporary), str(path))


def _load_checkpoint(path: Path, source_key: str = "") -> Mapping[str, Any]:
    import torch

    checkpoint = torch.load(path, map_location="cpu", weights_only=False)
    if not isinstance(checkpoint, Mapping):
        raise TypeError(f"{path}: checkpoint is not a mapping")
    if source_key:
        value = checkpoint
        for part in source_key.split("."):
            if not isinstance(value, Mapping) or part not in value:
                raise KeyError(f"{path}: checkpoint has no source key {source_key}")
            value = value[part]
        selected = value
    else:
        selected = checkpoint.get("state_dict", checkpoint)
    if not isinstance(selected, Mapping):
        raise TypeError(f"{path}: selected checkpoint state is not a mapping")
    return selected


def extract_backbone_state(state: Mapping[str, Any]) -> dict[str, Any]:
    import torch

    prefixes = (
        "backbone.",
        "module.backbone.",
        "model.backbone.",
        "student.backbone.",
        "teacher.backbone.",
    )
    extracted: dict[str, Any] = {}
    for key, value in state.items():
        if not torch.is_tensor(value):
            continue
        for prefix in prefixes:
            if str(key).startswith(prefix):
                output_key = str(key)[len(prefix):]
                extracted[output_key] = value.detach().cpu()
                break
    if not extracted:
        raise ValueError("No backbone tensors were found in the checkpoint")
    return extracted


def build_derived_config(
    base_config: str | Path,
    backbone_checkpoint: str | Path,
    backbone_type: str,
    save_best: str,
) -> str:
    if backbone_type not in BACKBONE_OPTIONS:
        raise ValueError(f"Unsupported backbone type: {backbone_type}")
    options = BACKBONE_OPTIONS[backbone_type]
    lines = [
        "# Generated by prepare_frozen_training.py",
        f"_base_ = [{str(Path(base_config).expanduser().resolve())!r}]",
        "",
        "model = dict(",
        "    backbone=dict(",
        f"        frozen_stages={int(options['frozen_stages'])},",
    ]
    if options["norm_eval"] is not None:
        lines.append(f"        norm_eval={bool(options['norm_eval'])},")
    lines.extend(
        [
            "        init_cfg=dict(",
            "            type='Pretrained',",
            "            checkpoint="
            + repr(str(Path(backbone_checkpoint).expanduser().resolve()))
            + ",",
            "        ),",
            "    ),",
            ")",
            "",
            "load_from = None",
            "resume = False",
            "",
            "default_hooks = dict(",
            "    checkpoint=dict(",
            f"        save_best={save_best!r},",
            "        save_last=True,",
            "        max_keep_ckpts=3,",
            "    ),",
            ")",
            "",
        ]
    )
    return "\n".join(lines)


def prepare(args: argparse.Namespace) -> None:
    base_config = _existing_file(args.base_config)
    detector_checkpoint = _existing_file(args.detector_checkpoint)
    backbone_output = Path(args.backbone_output).expanduser().resolve()
    config_output = Path(args.config_output).expanduser().resolve()
    for output in (backbone_output, config_output):
        if output.exists() and not args.overwrite:
            raise FileExistsError(f"Output exists; pass --overwrite: {output}")

    state = _load_checkpoint(detector_checkpoint, args.source_key)
    backbone = extract_backbone_state(state)
    _atomic_torch_save(
        {
            "state_dict": backbone,
            "meta": {
                "source_checkpoint": str(detector_checkpoint),
                "source_key": args.source_key or "auto",
                "backbone_type": args.backbone_type,
                "backbone_tensors": len(backbone),
            },
        },
        backbone_output,
    )
    config_text = build_derived_config(
        base_config=base_config,
        backbone_checkpoint=backbone_output,
        backbone_type=args.backbone_type,
        save_best=args.save_best,
    )
    _atomic_write(config_output, config_text)

    print(f"NAME={args.name}")
    print(f"DETECTOR_CHECKPOINT={detector_checkpoint}")
    print(f"BACKBONE={backbone_output}")
    print(f"CONFIG={config_output}")
    print(f"BACKBONE_TENSORS={len(backbone)}")
    print("RESULT=PASS_PREPARE_FROZEN_BACKBONE")


def verify(args: argparse.Namespace) -> None:
    import torch

    detector_checkpoint = _existing_file(args.checkpoint)
    backbone_path = _existing_file(args.backbone)
    detector_state = extract_backbone_state(_load_checkpoint(detector_checkpoint))
    backbone_checkpoint = _load_checkpoint(backbone_path)
    expected = backbone_checkpoint.get("state_dict", backbone_checkpoint)
    if set(detector_state) != set(expected):
        missing = sorted(set(expected) - set(detector_state))
        extra = sorted(set(detector_state) - set(expected))
        raise ValueError(
            f"Backbone key mismatch; missing={missing[:10]} extra={extra[:10]}"
        )
    mismatched = []
    for key in sorted(expected):
        left = detector_state[key]
        right = expected[key]
        if tuple(left.shape) != tuple(right.shape) or not torch.equal(left, right):
            mismatched.append(key)
    if mismatched:
        raise ValueError(f"Backbone tensors changed: {mismatched[:20]}")
    print(f"VERIFIED_CHECKPOINT={detector_checkpoint}")
    print(f"VERIFIED_BACKBONE={backbone_path}")
    print(f"BACKBONE_TENSORS={len(expected)}")
    print("RESULT=PASS_FROZEN_BACKBONE_UNCHANGED")


def main() -> None:
    args = parse_args()
    if args.command == "prepare":
        prepare(args)
    elif args.command == "verify":
        verify(args)
    else:
        raise ValueError(args.command)


if __name__ == "__main__":
    main()
